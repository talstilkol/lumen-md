// Writes the Shiki grammars from @shikijs/langs as JSON into
// public/shiki/langs/, so the render worker (plan 8.1 step 3) can highlight
// any language by fetching its grammar: the worker is one bundled script,
// in which an `import()` of a language module would be inlined — all 360
// of them.
//
//   onig.wasm                the Oniguruma regex engine (shiki/dist/onig.wasm)
//   langs/index.json         language or alias → the grammar names to
//                            register, in order (what the module's default
//                            export lists; embedded languages first)
//   langs/<grammar>.json     one TextMate grammar (a single registration)
//
// Each grammar is written once, however many languages embed it (as JSON
// per language it would be ~100 MB; this way it is 7.7 MB for 260
// grammars, of which a document fetches one file per grammar it needs).
// public/shiki/ is git-ignored, regenerated by predev/prebuild and excluded
// from the service worker's precache, like the main bundle's per-language
// chunks.
import { copyFileSync, existsSync, mkdirSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const distDir = join(here, "..", "node_modules", "@shikijs", "langs", "dist");
const outDir = join(here, "..", "public", "shiki", "langs");
const onigWasm = join(here, "..", "node_modules", "shiki", "dist", "onig.wasm");

/** A language module's registrations: the grammar names in order, and each grammar's JSON. */
export async function grammarsOf(name) {
  const mod = await import(pathToFileURL(join(distDir, `${name}.mjs`)).href);
  const order = [];
  const grammars = new Map();
  for (const reg of mod.default) {
    if (!grammars.has(reg.name)) {
      grammars.set(reg.name, JSON.stringify(reg));
      order.push(reg.name);
    }
  }
  return { order, grammars };
}

export async function copyShikiGrammars() {
  if (!existsSync(distDir)) {
    console.warn("copy-shiki-grammars: @shikijs/langs not installed — the render worker will highlight only its bundled languages");
    return 0;
  }
  mkdirSync(outDir, { recursive: true });
  const names = readdirSync(distDir)
    .filter((f) => f.endsWith(".mjs") && f !== "index.mjs")
    .map((f) => f.slice(0, -4));
  const index = {};
  const written = new Map();
  let total = 0;
  for (const name of names) {
    const { order, grammars } = await grammarsOf(name);
    index[name] = order;
    for (const [g, json] of grammars) {
      if (written.has(g)) {
        if (written.get(g) !== json) throw new Error(`copy-shiki-grammars: grammar "${g}" differs between language modules`);
        continue;
      }
      written.set(g, json);
      const dest = join(outDir, `${g}.json`);
      // The source is pinned by the lockfile: a file of the same size is current.
      if (!existsSync(dest) || statSync(dest).size !== Buffer.byteLength(json)) writeFileSync(dest, json);
      total += Buffer.byteLength(json);
    }
  }
  writeFileSync(join(outDir, "index.json"), JSON.stringify(index));
  // The Oniguruma engine's wasm, fetched by the worker on its first highlight.
  const wasmDest = join(here, "..", "public", "shiki", "onig.wasm");
  if (existsSync(onigWasm) && (!existsSync(wasmDest) || statSync(wasmDest).size !== statSync(onigWasm).size)) copyFileSync(onigWasm, wasmDest);
  console.log(`copy-shiki-grammars: ${names.length} languages, ${written.size} grammars → public/shiki/langs/ (${(total / 1e6).toFixed(1)} MB)`);
  return names.length;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) await copyShikiGrammars();
