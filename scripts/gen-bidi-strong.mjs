#!/usr/bin/env node
/**
 * Generates src/lib/bidiStrong.generated.ts (plan 9.7): which code points
 * are strong left-to-right (Bidi_Class L) or strong right-to-left (R, AL),
 * taken from bidi-js (MIT, a UAX #9 implementation with the Unicode
 * character data). The app ships only this ~1 KB table, not bidi-js;
 * src/__tests__/bidiDirection.test.ts re-derives it and fails on drift.
 *
 *   node scripts/gen-bidi-strong.mjs [--check]
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import bidiFactory from "bidi-js";

const OUT = join(dirname(fileURLToPath(import.meta.url)), "..", "src", "lib", "bidiStrong.generated.ts");

/** The encoded table: runs of `<base-36 length><N|L|R>` from U+0000. */
export function encodeStrongTable() {
  const bidi = bidiFactory();
  const cls = (cp) => {
    if (cp >= 0xd800 && cp <= 0xdfff) return "N";
    const t = bidi.getBidiCharTypeName(String.fromCodePoint(cp));
    return t === "L" ? "L" : t === "R" || t === "AL" ? "R" : "N";
  };
  let out = "";
  let prev = "N";
  let start = 0;
  for (let cp = 0; cp <= 0x110000; cp++) {
    const c = cp === 0x110000 ? "END" : cls(cp);
    if (c !== prev) {
      out += (cp - start).toString(36) + prev;
      start = cp;
      prev = c;
    }
  }
  return out;
}

export function render(table) {
  return `// Generated by scripts/gen-bidi-strong.mjs from bidi-js (MIT). Do not edit.
// Runs from U+0000: base-36 length, then N (not strong), L (Bidi_Class L) or R (R / AL).
export const BIDI_STRONG_RUNS =
  ${JSON.stringify(table)};
`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const text = render(encodeStrongTable());
  if (process.argv.includes("--check")) {
    const ok = readFileSync(OUT, "utf8") === text;
    console.log(ok ? "✓ bidiStrong.generated.ts is up to date" : "✗ bidiStrong.generated.ts is stale: run node scripts/gen-bidi-strong.mjs");
    process.exit(ok ? 0 : 1);
  }
  writeFileSync(OUT, text);
  console.log(`wrote ${OUT}`);
}
