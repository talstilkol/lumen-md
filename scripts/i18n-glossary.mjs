#!/usr/bin/env node
/**
 * The glossary gate (plan W13.I4), part of `npm run i18n:check`.
 *
 *   node scripts/i18n-glossary.mjs --check   exit 1 on any deviation, a broken glossary, or a stale docs table
 *   node scripts/i18n-glossary.mjs --write   rewrite the glossary tables of the Help translate pages
 *   node scripts/i18n-glossary.mjs --list    every deviation and warning, one per line
 *
 * i18n/glossary.json gives each Lumen term (vault, note, sync, property …) one approved
 * translation per language. A translation of a string that uses the term must use the
 * approved one ("כספת", never "מאגר"). The tables on the Help translate pages
 * (docs/…/contributing/translations.md, en and he) are generated from the file.
 * With nothing to check (no term, no translated string) the gate fails.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { argv, exit } from "node:process";
import { ROOT, listLocales, readLocale } from "./lib/i18n-files.mjs";
import { lazyEnglishEntries } from "./lib/i18n-lazy.mjs";
import { checkGlossary, glossaryShape, glossaryTable, readGlossary } from "./lib/i18n-glossary.mjs";

const args = new Set(argv.slice(2));
const glossary = readGlossary(ROOT);
const en = { ...readLocale("en"), ...Object.fromEntries(lazyEnglishEntries(ROOT)) };
const locales = Object.fromEntries(listLocales().filter((l) => l !== "en").map((l) => [l, readLocale(l)]));

export const DOCS = [
  { file: "docs/src/content/docs/contributing/translations.md", heading: "Term", meaning: "Meaning" },
  { file: "docs/src/content/docs/he/contributing/translations.md", heading: "מונח", meaning: "משמעות" },
];
const START = "<!-- glossary:start (generated by scripts/i18n-glossary.mjs --write) -->";
const END = "<!-- glossary:end -->";

function withTable(text, doc) {
  const a = text.indexOf(START);
  const b = text.indexOf(END);
  if (a < 0 || b < a) return null;
  return `${text.slice(0, a)}${START}\n\n${glossaryTable(glossary, doc)}\n\n${text.slice(b)}`;
}

const shape = glossaryShape(glossary);
const { deviations, checked } = checkGlossary({ glossary, en, locales });
const errors = deviations.filter((d) => d.level === "error");

if (args.has("--write")) {
  for (const doc of DOCS) {
    const path = join(ROOT, doc.file);
    const next = withTable(readFileSync(path, "utf8"), doc);
    if (next === null) {
      console.error(`✗ ${doc.file}: no glossary markers`);
      exit(1);
    }
    writeFileSync(path, next);
  }
  console.log(`✓ glossary tables written (${glossary.terms.length} terms)`);
} else if (args.has("--list")) {
  process.stdout.write(deviations.map((d) => `${d.level}\t${d.lang}\t${d.term}\t${d.key}\t${d.detail}\n`).join(""));
} else {
  const problems = [...shape];
  for (const doc of DOCS) {
    const text = readFileSync(join(ROOT, doc.file), "utf8");
    const next = withTable(text, doc);
    if (next === null) problems.push(`${doc.file}: no glossary table (markers missing)`);
    else if (next !== text) problems.push(`${doc.file}: the glossary table is stale — run node scripts/i18n-glossary.mjs --write`);
  }
  if (!checked) problems.push("nothing to check: no translated string uses a glossary term");
  for (const d of errors.slice(0, 200)) problems.push(`${d.lang} ${d.key} (${d.term}): ${d.kind} — ${d.detail}: “${d.value.slice(0, 80)}”`);
  if (problems.length) {
    for (const p of problems) console.error(`  ✗ ${p}`);
    console.error(`✗ glossary: ${errors.length} deviation(s), ${problems.length - Math.min(errors.length, 200)} other problem(s)`);
    exit(1);
  }
  console.log(`✓ glossary: ${glossary.terms.length} terms, ${checked} translations checked, 0 deviations (${deviations.length} warnings for terms with more than one sense)`);
}
