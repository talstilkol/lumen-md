#!/usr/bin/env node
/**
 * The two runner pages' scripts, prebuilt and committed (plan W10.D1).
 *
 * playground-runner.html and livejs-runner.html run in sandboxed,
 * opaque-origin frames. Their CSP allows their one script by its sha256 —
 * no 'self' (WebKit does not match it in an opaque-origin frame), no nonce
 * (one written in a public repository protects nothing) and no
 * 'strict-dynamic' (it would let the live-js worker importScripts() any URL).
 * A Vite chunk's bytes change with every build, so a hash in a header policy
 * written before the build cannot name it. These bundles are therefore built
 * here, committed under public/runners/ with fixed names, and their hashes
 * are pinned in security/policy.json and in each page's integrity attribute.
 *
 *   node scripts/build-runners.mjs           rebuild, pin the hashes, re-render every policy copy
 *   node scripts/build-runners.mjs --check   exit 1 when a bundle, page or policy is stale
 *
 * Deterministic: esbuild (the version below, from node_modules or
 * /opt/npm-tools), one IIFE per runner, no minification, paths relative to
 * the repository, no tsconfig but strict mode. A runner may import this repository's code
 * only — never a package — so the output depends on the sources and the
 * esbuild version alone. Each bundle's header lists its inputs with their
 * sha256, so src/__tests__/runnerBundles.test.ts can tell a stale bundle
 * from its sources even where esbuild is not installed, and rebuilds the
 * bytes where it is.
 */
import { createHash } from "node:crypto";
import { existsSync, readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join, relative, resolve, sep } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

export const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
/** The esbuild version the committed bundles were built with; another version may print different bytes. */
export const ESBUILD_VERSION = "0.28.2";
const TOOLS = "/opt/npm-tools/node_modules";

const rel = (url) => relative(ROOT, fileURLToPath(url)).split(sep).join("/");

/** Each runner: its entry module, its committed bundle, the page that loads it and the policy route. */
export const RUNNERS = [
  {
    name: "livejs-runner",
    entry: rel(new URL("../src/plugins/liveJsRunner.ts", import.meta.url)),
    out: "public/runners/livejs-runner.js",
    page: "public/livejs-runner.html",
    route: "livejs-runner",
  },
  {
    name: "playground-runner",
    entry: rel(new URL("../src/playground/runner.ts", import.meta.url)),
    out: "public/runners/playground-runner.js",
    page: "public/playground-runner.html",
    route: "playground-runner",
  },
];

/** The CSP / SRI form of a SHA-256: `sha256-<base64>`. */
export const sha256 = (bytes) => `sha256-${createHash("sha256").update(bytes).digest("base64")}`;

/** esbuild at ESBUILD_VERSION, or null with the reason. */
export async function loadEsbuild() {
  const tried = [];
  for (const base of [ROOT, TOOLS]) {
    let path;
    try {
      path = createRequire(join(base, "noop.js")).resolve("esbuild");
    } catch {
      tried.push(`${base}: no esbuild`);
      continue;
    }
    const mod = await import(pathToFileURL(path).href);
    const esbuild = mod.default ?? mod;
    if (esbuild.version === ESBUILD_VERSION) return { esbuild };
    tried.push(`${base}: esbuild ${esbuild.version}, not ${ESBUILD_VERSION}`);
  }
  return { esbuild: null, reason: tried.join("; ") };
}

/** The bundle header: what it was built from, so staleness shows without esbuild. */
export function header(runner, inputs) {
  return [
    `/* ${runner.out} — generated by scripts/build-runners.mjs (esbuild ${ESBUILD_VERSION}). Do not edit:`,
    ` * change the sources and run \`node scripts/build-runners.mjs\` (plan W10.D1).`,
    ` * The page's CSP allows this file by its sha256 (security/policy.json, route ${runner.route}).`,
    ...inputs.map((f) => ` * input ${f} ${sha256(readFileSync(join(ROOT, f)))}`),
    ` */`,
    "",
  ].join("\n");
}

/** The inputs a committed bundle's header lists: [{ file, hash }]. */
export function headerInputs(text) {
  return [...text.matchAll(/^ \* input (\S+) (sha256-\S+)$/gm)].map((m) => ({ file: m[1], hash: m[2] }));
}

/**
 * The inputs of a committed bundle whose source changed since it was built
 * (or that is gone): [{ file, built, now }]. Needs no esbuild. `read` gives a
 * file's bytes, or null when it doesn't exist.
 */
export function staleInputs(bundleText, read = (f) => (existsSync(join(ROOT, f)) ? readFileSync(join(ROOT, f)) : null)) {
  const out = [];
  for (const { file, hash } of headerInputs(bundleText)) {
    const bytes = read(file);
    const now = bytes === null ? null : sha256(bytes);
    if (now !== hash) out.push({ file, built: hash, now });
  }
  return out;
}

/** Build one runner: the exact bytes that belong in runner.out. */
export async function buildRunner(esbuild, runner) {
  const result = await esbuild.build({
    absWorkingDir: ROOT,
    entryPoints: [runner.entry],
    bundle: true,
    write: false,
    format: "iife",
    platform: "browser",
    target: "es2022",
    charset: "utf8",
    legalComments: "none",
    minify: false,
    tsconfigRaw: { compilerOptions: { alwaysStrict: true } },
    metafile: true,
    logLevel: "silent",
  });
  const inputs = Object.keys(result.metafile.inputs).sort();
  const pkgs = inputs.filter((f) => /(^|\/)node_modules\//.test(f));
  if (pkgs.length) throw new Error(`${runner.entry}: a runner may import only this repository's code, not ${pkgs.join(", ")}`);
  return header(runner, inputs) + result.outputFiles[0].text;
}

/** The page's <script> for its bundle (relative: a subpath deployment serves both beneath its base). */
export const scriptTag = (runner, hash) =>
  `<script src="runners/${runner.name}.js" integrity="${hash}" crossorigin="anonymous"></script>`;
const SCRIPT_TAG_RE = (runner) => new RegExp(`<script src="runners/${runner.name}\\.js" integrity="[^"]*" crossorigin="anonymous"></script>`);

/** The route's script-src hash in security/policy.json's text, replaced (the file keeps its formatting). */
export function pinPolicyHash(policyText, route, hash) {
  const at = policyText.indexOf(`"${route}": {`);
  if (at < 0) throw new Error(`security/policy.json: no route ${route}`);
  const open = policyText.indexOf(`"script-src": [`, at);
  const close = policyText.indexOf("]", open);
  const block = policyText.slice(open, close);
  if ((block.match(/'sha256-/g) ?? []).length !== 1) throw new Error(`security/policy.json: route ${route} needs exactly one 'sha256-…' in script-src`);
  return policyText.slice(0, open) + block.replace(/'sha256-[^']*'/, `'${hash}'`) + policyText.slice(close);
}

/** Every file this script owns, as it should be: { path: text }. */
export async function expectedFiles(esbuild) {
  const out = {};
  let policy = readFileSync(join(ROOT, "security/policy.json"), "utf8");
  for (const runner of RUNNERS) {
    const code = await buildRunner(esbuild, runner);
    const hash = sha256(code);
    out[runner.out] = code;
    const page = readFileSync(join(ROOT, runner.page), "utf8");
    if (!SCRIPT_TAG_RE(runner).test(page)) throw new Error(`${runner.page}: expected one ${scriptTag(runner, "sha256-…")}`);
    out[runner.page] = page.replace(SCRIPT_TAG_RE(runner), scriptTag(runner, hash));
    policy = pinPolicyHash(policy, runner.route, hash);
  }
  out["security/policy.json"] = policy;
  return out;
}

async function main(argv) {
  const check = argv.includes("--check");
  const { esbuild, reason } = await loadEsbuild();
  if (!esbuild) {
    console.error(`build-runners: needs esbuild ${ESBUILD_VERSION} (${reason})`);
    return 2;
  }
  const files = await expectedFiles(esbuild);
  const stale = Object.entries(files).filter(([f, text]) => !existsSync(join(ROOT, f)) || readFileSync(join(ROOT, f), "utf8") !== text);
  if (check) {
    for (const [f] of stale) console.error(`build-runners: ${f} is stale — run node scripts/build-runners.mjs`);
    if (!stale.length) console.log(`build-runners: ${RUNNERS.length} bundles, pages and hashes are current`);
    return stale.length ? 1 : 0;
  }
  for (const [f, text] of stale) {
    mkdirSync(dirname(join(ROOT, f)), { recursive: true });
    writeFileSync(join(ROOT, f), text);
    console.log(`build-runners: wrote ${f}`);
  }
  // Render the new hashes into every copy of the policy (headers, nginx, Vercel, meta).
  const { run } = await import("./headers.mjs");
  run({ write: true });
  const { problems } = run({ write: false });
  for (const p of problems) console.error(`headers: ${p}`);
  return problems.length ? 1 : 0;
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  process.exit(await main(process.argv.slice(2)));
}
