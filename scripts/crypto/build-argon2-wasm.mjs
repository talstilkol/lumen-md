#!/usr/bin/env node
/**
 * Build the Argon2id memory fill (src/sync/e2ee/primitives/wasm/argon2fill.c)
 * to WebAssembly and embed it in src/sync/e2ee/primitives/wasm/argon2fillWasm.ts
 * (plan W4.20). No package: clang's wasm32 target and wasm-ld, which LLVM
 * ships (Xcode's clang has no wasm32 target: `brew install llvm`).
 *
 *   node scripts/crypto/build-argon2-wasm.mjs           # rebuild and rewrite the .ts
 *   node scripts/crypto/build-argon2-wasm.mjs --check   # rebuild; exit 1 if the embedded bytes differ
 *
 * The flags pin the output: the MVP feature set (every engine the app runs
 * in), no standard library, no builtins (no memcpy/memset calls), stripped.
 * The same clang major gives the same bytes; the .ts records the sha256 and
 * the clang version it was built with, and the unit test checks the sha256.
 */
import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..", "..");
const SRC = join(ROOT, "src/sync/e2ee/primitives/wasm/argon2fill.c");
const OUT = join(ROOT, "src/sync/e2ee/primitives/wasm/argon2fillWasm.ts");
export const FLAGS = ["--target=wasm32", "-mcpu=mvp", "-O3", "-nostdlib", "-fno-builtin", "-ffile-prefix-map=" + ROOT + "=.", "-Wl,--no-entry", "-Wl,--export=fill", "-Wl,--export=__heap_base", "-Wl,--strip-all"];

export function build(clang = process.env.CLANG ?? "clang") {
  const dir = mkdtempSync(join(tmpdir(), "argon2-wasm-"));
  try {
    const wasm = join(dir, "argon2fill.wasm");
    execFileSync(clang, [...FLAGS, "-o", wasm, SRC], { stdio: ["ignore", "ignore", "inherit"] });
    const version = execFileSync(clang, ["--version"], { encoding: "utf8" }).split("\n")[0].trim();
    return { bytes: readFileSync(wasm), version };
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
}

export function render(bytes, version) {
  const sha = createHash("sha256").update(bytes).digest("hex");
  const b64 = bytes.toString("base64");
  const lines = b64.match(/.{1,120}/g) ?? [];
  return `/**
 * Generated by scripts/crypto/build-argon2-wasm.mjs from ./argon2fill.c — do not edit.
 * ${bytes.length} bytes, sha256 ${sha}
 * built with ${version}
 */
export const ARGON2_FILL_WASM_SHA256 = "${sha}";
export const ARGON2_FILL_WASM_B64 =
${lines.map((l, i) => `  "${l}"${i === lines.length - 1 ? ";" : " +"}`).join("\n")}
`;
}

/** The sha256 the embedded module records, and the one its bytes have. */
export function embedded(text = readFileSync(OUT, "utf8")) {
  const recorded = /ARGON2_FILL_WASM_SHA256 = "([0-9a-f]{64})"/.exec(text)?.[1] ?? null;
  const b64 = [...text.slice(text.indexOf("ARGON2_FILL_WASM_B64")).matchAll(/"([A-Za-z0-9+/=]+)"/g)].map((m) => m[1]).join("");
  const actual = createHash("sha256").update(Buffer.from(b64, "base64")).digest("hex");
  return { recorded, actual };
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const { bytes, version } = build();
  const sha = createHash("sha256").update(bytes).digest("hex");
  if (process.argv.includes("--check")) {
    const e = embedded();
    const ok = e.recorded === sha && e.actual === sha;
    console.log(ok ? `ok: the embedded Argon2 fill is this build (${sha})` : `differs: built ${sha}, embedded ${e.actual} (recorded ${e.recorded}) — ${version}`);
    process.exit(ok ? 0 : 1);
  }
  writeFileSync(OUT, render(bytes, version));
  console.log(`wrote ${OUT}: ${bytes.length} bytes, sha256 ${sha}`);
}
