const LUMEN_8 = new Set(["he", "en", "ar", "ru", "fr", "de", "ja", "zh"]);

export const hard = {
  pool() {
    if (CASES.length !== 90) throw new Error(`langid/hard: ${CASES.length} cases, want 90`);
    const items = CASES.map(([lang, text, note], i) => ({ id: `hard-${String(i + 1).padStart(2, "0")}`, text, lang, scope: lang === "und" ? "none" : LUMEN_8.has(lang) ? "lumen-8" : "other", note }));
    return { items };
  },
  select: (pool, opts) => splitPool(pool.items, opts),
  meta: () => ({
    source: { sampling: "a pool of 90 cases written for this set by the golden-set agent (CC0 1.0); dev and test drawn by splitPool" },
    fields: { text: "the string", lang: "expected BCP-47 primary tag (und = no language)", scope: "lumen-8 | other | none", note: "why it is hard" },
  }),
};
