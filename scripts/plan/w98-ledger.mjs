#!/usr/bin/env node
/**
 * W9.8: a row-by-row proof that every needs-code = y decision of #618
 * (plan/decisions-2026-11-14.md) has its code and test, or says why not.
 *
 *   node scripts/plan/w98-ledger.mjs                 check plan/w98-ledger.json against the decisions and the tree
 *   node scripts/plan/w98-ledger.mjs --runner <cmd>  also run every cited test, by its name (<cmd> <root> <file> <name regex>, last line "… pass N fail M")
 *   node scripts/plan/w98-ledger.mjs --markdown      the table, for plan/w98-ledger.md
 *
 * The check fails (exit 1) when:
 * - a needs-code = y row has no ledger row, or the ledger has a row that is not one;
 * - a `done` row has a commit that is not an ancestor of HEAD;
 * - a cited test file is missing, or does not hold the named test;
 * - a probe's file does not hold its text;
 * - a `done` row has neither a test nor a probe;
 * - with --runner, a cited test has a failure or no passing test. A test
 *   that lists `needs` (packages) and finds one stubbed by the runner is
 *   reported "not here": no proof, not a red, owed where it is installed.
 * deps-train, owner-act and open rows need a note saying what is owed.
 */
import { execFileSync, spawnSync } from "node:child_process";
import { existsSync, readFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(fileURLToPath(new URL("../..", import.meta.url)));
export const DECISIONS = "plan/decisions-2026-11-14.md";
export const LEDGER = "plan/w98-ledger.json";
const STATUSES = new Set(["done", "deps-train", "owner-act", "open"]);

/** The needs-code = y rows of the decisions table: [{ step, pr, finding }]. */
export function needsCodeRows(md) {
  const out = [];
  for (const line of md.split("\n")) {
    const cells = line.split("|").map((c) => c.trim());
    // | step | PR | question | decision | reason | needs-code | kind |
    if (cells.length < 9 || !/^\d+\.\d+$/.test(cells[1])) continue;
    if (cells[6] === "y") out.push({ step: cells[1], pr: cells[2], finding: cells[3] });
  }
  return out;
}

/**
 * Problems of the ledger, with no git or test run (those are passed in).
 * @param {{ rows: Record<string, any> }} ledger
 * @param {Array<{ step: string }>} wanted
 * @param {{ isAncestor: (c: string) => boolean, read: (f: string) => string | null }} io
 */
export function ledgerProblems(ledger, wanted, io) {
  const p = [];
  const rows = ledger?.rows ?? {};
  const steps = new Set(wanted.map((w) => w.step));
  for (const w of wanted) if (!(w.step in rows)) p.push(`${w.step}: a needs-code row with no ledger row`);
  for (const step of Object.keys(rows)) if (!steps.has(step)) p.push(`${step}: in the ledger but not a needs-code = y row`);
  for (const [step, r] of Object.entries(rows)) {
    if (!STATUSES.has(r.status)) {
      p.push(`${step}: status ${JSON.stringify(r.status)} is not one of ${[...STATUSES].join(", ")}`);
      continue;
    }
    if (r.status !== "done") {
      if (!(typeof r.note === "string" && r.note.trim())) p.push(`${step}: a ${r.status} row must say what is owed (note)`);
      continue;
    }
    const tests = r.tests ?? [];
    const probes = r.probes ?? [];
    if (!tests.length && !probes.length) p.push(`${step}: done, with neither a test nor a probe`);
    for (const c of r.commits ?? []) if (!io.isAncestor(c)) p.push(`${step}: commit ${c} is not an ancestor of HEAD`);
    for (const t of tests) {
      const text = io.read(t.file);
      if (text === null) p.push(`${step}: test file ${t.file} is missing`);
      else if (t.match && !text.includes(t.match)) p.push(`${step}: ${t.file} holds no test ${JSON.stringify(t.match)}`);
    }
    for (const pr of probes) {
      const text = io.read(pr.file);
      if (text === null) p.push(`${step}: probe file ${pr.file} is missing`);
      else if (!text.includes(pr.contains)) p.push(`${step}: ${pr.file} does not hold ${JSON.stringify(pr.contains.slice(0, 60))}`);
    }
  }
  return p;
}

/** How many rows are in each status. */
export function counts(ledger) {
  const c = { done: 0, "deps-train": 0, "owner-act": 0, open: 0 };
  for (const r of Object.values(ledger.rows)) c[r.status] = (c[r.status] ?? 0) + 1;
  return c;
}

export function markdown(ledger, wanted, results = new Map()) {
  const c = counts(ledger);
  const o = [`# W9.8 ledger: the ${wanted.length} needs-code decisions of #618`, "", "Generated by `node scripts/plan/w98-ledger.mjs --markdown` from plan/w98-ledger.json; the check (`node scripts/plan/w98-ledger.mjs [--runner <shim>]`) fails on a missing row, a commit that is not in the train, or a cited test that is missing or red.", "", `**${c.done} done** (commit in the train + a named test or probe) · **${c["deps-train"]} deps train** · **${c["owner-act"]} owner-act** · **${c.open} open**`, "", "| step | PR | finding | status | commits | proof | note |", "|---|---|---|---|---|---|---|"];
  const cell = (s) => String(s ?? "").replace(/\|/g, "\\|").replace(/\n/g, " ");
  for (const w of wanted) {
    const r = ledger.rows[w.step];
    const proof = [...(r.tests ?? []).map((t) => `${t.file.split("/").pop()}${t.match ? ` "${t.match.slice(0, 50)}"` : ""}${results.has(`${t.file}\0${t.match ?? ""}`) ? ` (${results.get(`${t.file}\0${t.match ?? ""}`)})` : ""}`), ...(r.probes ?? []).map((pr) => `${pr.file} holds "${pr.contains.slice(0, 40)}…"`)].join("; ");
    o.push(`| ${w.step} | ${w.pr} | ${cell(w.finding.slice(0, 70))} | ${r.status} | ${(r.commits ?? []).join(", ")} | ${cell(proof)} | ${cell(r.note)} |`);
  }
  return `${o.join("\n")}\n`;
}

/**
 * The runner's name filter for one cited test: the title as a regex, with
 * the characters a shell would split or glob on (the shim passes its filter
 * unquoted) matched by "." instead.
 */
export function nameFilter(title) {
  return title.replace(/[.+^${}()|\\]/g, "\\$&").replace(/[\s*?[\]'"`;&<>!#~]/g, ".");
}

function main(argv) {
  const read = (f) => (existsSync(join(ROOT, f)) ? readFileSync(join(ROOT, f), "utf8") : null);
  const wanted = needsCodeRows(read(DECISIONS) ?? "");
  const ledger = JSON.parse(read(LEDGER) ?? "{}");
  const isAncestor = (c) => {
    try {
      execFileSync("git", ["merge-base", "--is-ancestor", c, "HEAD"], { cwd: ROOT, stdio: "ignore" });
      return true;
    } catch {
      return false;
    }
  };
  const problems = ledgerProblems(ledger, wanted, { isAncestor, read });
  const results = new Map();
  const notHere = [];
  const ri = argv.indexOf("--runner");
  if (ri >= 0) {
    const runner = argv[ri + 1];
    const entries = new Map();
    for (const r of Object.values(ledger.rows ?? {})) if (r.status === "done") for (const t of r.tests ?? []) entries.set(`${t.file}\0${t.match ?? ""}`, t);
    for (const t of [...entries.values()].sort((a, b) => `${a.file}${a.match}`.localeCompare(`${b.file}${b.match}`))) {
      const r = spawnSync(runner, [ROOT, t.file, ...(t.match ? [nameFilter(t.match)] : [])], { encoding: "utf8", maxBuffer: 256 * 1024 * 1024, timeout: 900_000 });
      const m = /pass (\d+) fail (\d+)\s*$/m.exec((r.stdout ?? "").trim().split("\n").filter((l) => /pass \d+ fail \d+/.test(l)).pop() ?? "");
      const out = `${r.stdout ?? ""}${r.stderr ?? ""}`;
      // A test that needs a package this runner stubs is "not here": no proof, and not a red (it runs on the Mac).
      const missing = (t.needs ?? []).filter((n) => out.includes(`stubbed package ${n}`));
      const res = missing.length ? `not here: needs ${missing.join(", ")}` : m ? `${m[1]}/${Number(m[1]) + Number(m[2])}` : "load error";
      results.set(`${t.file}\0${t.match ?? ""}`, res);
      console.error(`  ${t.file}${t.match ? ` "${t.match}"` : ""}: ${res}`);
      if (missing.length) notHere.push(`${t.file} "${t.match}"`);
      else if (!m || Number(m[2]) > 0 || Number(m[1]) === 0) problems.push(`${t.file}${t.match ? ` "${t.match}"` : ""}: ${m ? `${m[2]} failed of ${Number(m[1]) + Number(m[2])}` : "did not load"} (runner)`);
    }
  }
  if (argv.includes("--markdown")) process.stdout.write(markdown(ledger, wanted, results));
  const c = counts(ledger);
  console.error(`w98-ledger: ${wanted.length} needs-code rows — ${c.done} done, ${c["deps-train"]} deps train, ${c["owner-act"]} owner-act, ${c.open} open${ri >= 0 ? `; ${results.size} cited tests run${notHere.length ? `, ${notHere.length} not here (they need a package this runner stubs; owed on the Mac)` : ""}` : ""}`);
  for (const pr of problems) console.error(`✗ ${pr}`);
  return problems.length ? 1 : 0;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) process.exitCode = main(process.argv.slice(2));
