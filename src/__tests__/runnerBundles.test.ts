// @vitest-environment node
/**
 * Plan W10.D1 — the runner pages' prebuilt scripts and the hashes that pin
 * them (scripts/build-runners.mjs).
 *
 *   - each runner route's script-src is the bundle's sha256, blob: and eval:
 *     no 'self', no nonce, no 'strict-dynamic', on every host;
 *   - the page loads exactly that file, with the same hash as its integrity;
 *   - a bundle is stale when a source it lists changed (no esbuild needed),
 *     and, where esbuild at the pinned version is installed, rebuilding gives
 *     the committed bytes;
 *   - the live-js worker still has no way to load a script by URL.
 */
import { describe, it, expect } from "vitest";
import { readFileSync } from "node:fs";
import { join } from "node:path";
// @ts-expect-error — plain .mjs build script without types
import { loadPolicy, renderCsp, parseCsp, run as checkHeaders } from "../../scripts/headers.mjs";
import {
  RUNNERS,
  ESBUILD_VERSION,
  sha256,
  headerInputs,
  staleInputs,
  pinPolicyHash,
  loadEsbuild,
  expectedFiles,
  // @ts-expect-error — plain .mjs build script without types
} from "../../scripts/build-runners.mjs";

type Runner = { name: string; entry: string; out: string; page: string; route: string };
const root = join(__dirname, "..", "..");
const read = (f: string) => readFileSync(join(root, f), "utf8");
const policy = loadPolicy(root);
const runners = RUNNERS as Runner[];
const HOSTS = ["cloudflare", "vercel", "netlify", "deploy-nginx", "meta"];
const { esbuild, reason } = (await loadEsbuild()) as { esbuild: unknown; reason?: string };

describe.each(runners)("$name", (r) => {
  const bundle = read(r.out);
  const hash = sha256(bundle);

  it("script-src is the bundle's sha256, blob: and eval only — on every host", () => {
    for (const host of HOSTS) {
      const src = (parseCsp(renderCsp(policy, r.route, host)) as Map<string, string[]>).get("script-src");
      expect(src, host).toEqual([`'${hash}'`, "blob:", "'unsafe-eval'"]);
    }
  });

  it("every rendered copy carries that hash and no nonce", () => {
    expect(checkHeaders({ root }).problems).toEqual([]);
    for (const f of Object.keys(policy.sources)) {
      const text = read(f);
      expect(text, f).not.toMatch(/'nonce-/);
    }
    // No route, on no host, allows by nonce or by 'strict-dynamic'.
    for (const route of Object.keys(policy.routes)) {
      for (const host of HOSTS) {
        const csp = renderCsp(policy, route, host) as string;
        expect(csp, `${route} ${host}`).not.toMatch(/'nonce-|'strict-dynamic'/);
      }
    }
    for (const f of ["public/_headers", "deploy/vercel.base.json", "deploy/nginx.conf", "netlify/edge-functions/runner-headers.ts", r.page]) {
      expect(read(f), f).toContain(`'${hash}'`);
    }
  });

  it("the page loads exactly that file, by the same hash, and has no other script", () => {
    const page = read(r.page);
    const scripts = [...page.matchAll(/<script\b[^>]*>/g)].map((m) => m[0]);
    expect(scripts).toEqual([`<script src="runners/${r.name}.js" integrity="${hash}" crossorigin="anonymous">`]);
    expect(page).not.toMatch(/<script\b[^>]*>[^<\s]/); // nothing inline
    expect(page).not.toMatch(/nonce[="-]/i);
  });

  it("the bundle lists its inputs, all of them this repository's code, none changed since the build", () => {
    const inputs = headerInputs(bundle) as Array<{ file: string; hash: string }>;
    expect(inputs.map((i) => i.file)).toContain(r.entry);
    for (const { file } of inputs) expect(file).toMatch(/^src\//);
    expect(staleInputs(bundle)).toEqual([]);
    expect(bundle.startsWith(`/* ${r.out} — generated by scripts/build-runners.mjs (esbuild ${ESBUILD_VERSION}).`)).toBe(true);
  });

  it("a changed source makes the bundle stale", () => {
    const [first] = headerInputs(bundle) as Array<{ file: string }>;
    const edited = (f: string) => Buffer.from(f === first.file ? read(f) + "\n" : read(f));
    expect(staleInputs(bundle, edited)).toEqual([{ file: first.file, built: expect.stringMatching(/^sha256-/), now: expect.stringMatching(/^sha256-/) }]);
    expect(staleInputs(bundle, (f: string) => (f === first.file ? null : Buffer.from(read(f))))).toEqual([{ file: first.file, built: expect.any(String), now: null }]);
  });

  it("a changed byte in the bundle no longer matches the pinned hash", () => {
    expect(sha256(bundle.replace("(() => {", "(() =>  {"))).not.toBe(hash);
  });

  it("is served with CORS (the page loads it with integrity from an opaque origin)", () => {
    expect(read("public/_headers")).toMatch(/\n\/runners\/\*\n {2}Access-Control-Allow-Origin: \*\n/);
    const vercel = JSON.parse(read("deploy/vercel.base.json")) as { headers: { source: string; headers: { key: string; value: string }[] }[] };
    expect(vercel.headers.find((h) => h.source === "/runners/(.*)")?.headers).toContainEqual({ key: "Access-Control-Allow-Origin", value: "*" });
    expect(read("deploy/nginx.conf")).toMatch(/location \^~ \/runners\/ \{[^}]*Access-Control-Allow-Origin "\*"/);
  });
});

describe("freshness: rebuilding gives the committed bytes", () => {
  // skip-reason: the freshness check rebuilds with the pinned esbuild, which must be installed at that version; the reason is printed in the title | task: W10.D1 | until: 2027-05-16
  it.skipIf(!esbuild)(`with esbuild ${ESBUILD_VERSION}${esbuild ? "" : ` — skipped: ${reason}`}`, async () => {
    const files = (await expectedFiles(esbuild)) as Record<string, string>;
    expect(Object.keys(files).sort()).toEqual([...runners.flatMap((r) => [r.out, r.page]), "security/policy.json"].sort());
    for (const [f, text] of Object.entries(files)) expect(read(f) === text, `${f} is stale: run node scripts/build-runners.mjs`).toBe(true);
  });
});

describe("pinPolicyHash", () => {
  it("replaces the route's one hash and keeps the file's formatting", () => {
    const text = read("security/policy.json");
    const out = pinPolicyHash(text, "livejs-runner", "sha256-AAAA") as string;
    expect(out.length - text.length).toBe("sha256-AAAA".length - sha256(read("public/runners/livejs-runner.js")).length);
    expect(JSON.parse(out).routes["livejs-runner"].csp["script-src"]).toEqual(["'sha256-AAAA'", "blob:", "'unsafe-eval'"]);
    expect(JSON.parse(out).routes["playground-runner"].csp).toEqual(policy.routes["playground-runner"].csp);
  });

  it("refuses a route without exactly one hash", () => {
    expect(() => pinPolicyHash(read("security/policy.json"), "app", "sha256-AAAA")).toThrow(/exactly one/);
  });
});

describe("live-js: still no network at all", () => {
  const bundle = read("public/runners/livejs-runner.js");
  const csp = parseCsp(renderCsp(policy, "livejs-runner", "vercel")) as Map<string, string[]>;

  it("no source in script-src or worker-src can name a URL: the worker can only be the runner's blob:", () => {
    expect(csp.get("worker-src")).toEqual(["blob:"]);
    expect(csp.get("connect-src")).toEqual(["'none'"]);
    for (const s of csp.get("script-src")!) expect(s).toMatch(/^'sha256-|^blob:$|^'unsafe-eval'$/);
  });

  it("the runner starts the worker from a blob: of its own source and calls no importScripts", () => {
    const runner = bundle.slice(bundle.indexOf("// src/plugins/liveJsRunner.ts"));
    expect(runner).toMatch(/new Worker\(url, \{ type: "classic" \}\)/);
    expect(runner).toMatch(/URL\.createObjectURL\(new Blob\(\[WORKER_SOURCE\]/);
    // The only mention is the worker's lockdown list, which deletes it.
    expect(bundle.match(/importScripts/g)).toHaveLength(1);
    expect(bundle).toMatch(/"importScripts", "indexedDB"/);
  });
});

describe("playground runner: loads nothing by URL", () => {
  const bundle = read("public/runners/playground-runner.js");
  it("no fetch, no vendor URL, no parser or transpiler in the bundle", () => {
    expect(bundle).not.toMatch(/\bfetch\(|XMLHttpRequest|importScripts|playground\/vendor\/[a-z]/);
    expect(bundle).not.toMatch(/sucrase|acorn/i);
    // Every script it adds is a blob: URL.
    expect(bundle).toMatch(/s\.src = blob\(code\)/);
  });
});
