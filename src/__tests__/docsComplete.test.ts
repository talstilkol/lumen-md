/**
 * Plan 13.1 — docs-complete: the rules of scripts/docs-complete.mjs on small
 * in-memory doc trees (the real tree is checked by `npm run docs:complete`).
 */
import { describe, expect, it } from "vitest";
// @ts-expect-error — plain .mjs script without types
import { check, sidebarOf } from "../../scripts/docs-complete.mjs";

const CONFIG = `
sidebar: [
  { label: "A", items: [
    { label: "Intro", slug: "start/intro" },
    { label: "Sync", slug: "sync/git" },
  ] },
  { label: "Blocks", items: [{ autogenerate: { directory: "blocks" } }] },
]`;

function tree(files: Record<string, string>) {
  return {
    has: (rel: string) => rel in files,
    list: (dir: string) => Object.keys(files).filter((f) => f.startsWith(dir + "/")).map((f) => f.slice(dir.length + 1)),
    pages: Object.keys(files),
    read: (rel: string) => files[rel] ?? "",
  };
}

const ALL = {
  "start/intro.md": "See [git](/sync/git/).",
  "he/start/intro.md": "ראו [git](/he/sync/git/).",
  "sync/git.md": "",
  "he/sync/git.md": "",
  "blocks/ref.md": "",
  "he/blocks/ref.md": "",
  "index.mdx": "",
};

describe("docs-complete (plan 13.1)", () => {
  it("reads sidebar slugs and autogenerated directories", () => {
    expect(sidebarOf(CONFIG)).toEqual({ slugs: ["start/intro", "sync/git"], dirs: ["blocks"] });
  });

  it("a complete tree passes", () => {
    expect(check({ config: CONFIG, required: { areas: { intro: "start/intro" } }, ...tree(ALL) })).toEqual([]);
  });

  it("finds a missing English page, a missing Hebrew twin, and an untranslated autogenerated page", () => {
    const files: Record<string, string> = { ...ALL };
    delete files["sync/git.md"];
    delete files["he/start/intro.md"];
    delete files["he/blocks/ref.md"];
    files["start/intro.md"] = "";
    const problems = check({ config: CONFIG, required: {}, ...tree(files) });
    expect(problems).toEqual(
      expect.arrayContaining([
        expect.stringMatching(/^sync\/git: in the sidebar, but there is no English page/),
        expect.stringMatching(/^start\/intro: no Hebrew page/),
        expect.stringMatching(/^blocks\/ref\.md: no Hebrew page/),
      ]),
    );
  });

  it("an area 13.1.1 names must map to a sidebar page", () => {
    expect(check({ config: CONFIG, required: { areas: { privacy: "ai/privacy" } }, ...tree(ALL) })).toEqual([
      'area "privacy": its page ai/privacy is not in the sidebar',
    ]);
  });

  it("an orphan page (exists, not linked from the sidebar) is reported", () => {
    const problems = check({ config: CONFIG, required: {}, ...tree({ ...ALL, "ai/local-agents.md": "" }) });
    expect(problems).toEqual(["ai/local-agents: the page exists but nothing in the sidebar links to it"]);
  });

  it("internal links must resolve, and Hebrew pages link to Hebrew twins", () => {
    const problems = check({
      config: CONFIG,
      required: {},
      ...tree({ ...ALL, "start/intro.md": "[x](/collab/persistent/) [img](/img/a.png)", "he/start/intro.md": "[git](/sync/git/)" }),
    });
    expect(problems).toEqual([
      "start/intro.md: link /collab/persistent/ — no such page",
      "he/start/intro.md: link /sync/git/ — a Hebrew page links to /he/sync/git/",
    ]);
  });

  it("pending pages are exempt until they land, then must be unlisted", () => {
    const files: Record<string, string> = { ...ALL };
    delete files["sync/git.md"];
    delete files["he/sync/git.md"];
    const pending = { pending: { "sync/git": "#269" } };
    expect(check({ config: CONFIG, required: pending, ...tree(files) })).toEqual([]);
    expect(check({ config: CONFIG, required: pending, ...tree(ALL) })).toEqual([
      'sync/git: is listed as pending (#269) but the page exists — remove it from docs/required-pages.json "pending"',
    ]);
  });

  it("a Hebrew twin owed by another PR is exempt, and must be unlisted once it exists", () => {
    const files: Record<string, string> = { ...ALL };
    delete files["he/sync/git.md"];
    files["he/start/intro.md"] = "";
    const req = { hebrewPending: { "sync/git": "S5b" } };
    expect(check({ config: CONFIG, required: req, ...tree(files) })).toEqual([]);
    expect(check({ config: CONFIG, required: req, ...tree(ALL) })).toEqual(['sync/git: Hebrew page exists — remove it from "hebrewPending"']);
  });
});
