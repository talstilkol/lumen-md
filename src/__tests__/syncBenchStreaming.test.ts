/**
 * The sync benchmark with 1 GB of attachments was killed by the OOM killer on
 * a 7 GB machine (L4, rc 137). Measured on this branch's base: peak resident
 * size 657 MB at 128 MB of attachments and 1,074 MB at 256 MB, about 4× the
 * attachments. The engine holds one file at a time; the benchmark's own
 * stores held every byte three times (device A, the server, device B). The
 * streaming stores (scripts/bench/sync-bench-store.ts) keep it flat: 315 MB
 * at 256 MB and 336 MB at 1 GB.
 *
 * This runs the real engine and WebDAV provider (in process) over those
 * stores and checks that none of them keeps attachment bytes, and that what
 * B received is what A sent.
 */
import { describe, expect, it } from "vitest";
import { createHash } from "node:crypto";
import { createVault, unlockVault, E2eeSync } from "../sync/e2ee/engine";
import { memoryFiles } from "../sync/e2ee/localFiles";
import { memoryStateStore } from "../sync/e2ee/state";
import { webdavProvider } from "../sync/e2ee/providers/webdav";
import { fakeWebdav } from "./helpers/fakeServers/webdav";
import { fakeFetch } from "./helpers/fakeServers/http";
import { attachmentBytes, hashOnlyFiles, spillToDisk, virtualAttachments } from "../../scripts/bench/sync-bench-store";

const URL_ = "https://dav.example/dav/bench/Lumen/";
const MB = 1024 * 1024;

describe("sync benchmark: streaming stores (bench OOM at 1 GB)", () => {
  it("generates the same bytes for (seed, index), and different bytes otherwise", () => {
    const a = attachmentBytes(7, 3, 4096);
    expect(attachmentBytes(7, 3, 4096)).toEqual(a);
    expect(attachmentBytes(7, 4, 4096)).not.toEqual(a);
    expect(attachmentBytes(8, 3, 4096)).not.toEqual(a);
    expect(a.length).toBe(4096);
  });

  it("A's listing hashes the generated bytes without holding them", async () => {
    const v = virtualAttachments(memoryFiles(), { seed: 1, count: 2, each: 3 * MB + 5 });
    const list = await v.list();
    const bytes = (await v.read("attachments/file-1.bin"))!;
    expect(bytes.length).toBe(3 * MB + 5);
    expect(list.find((f) => f.path === "attachments/file-1.bin")!.hash).toBe(createHash("sha256").update(bytes).digest("hex"));
    await expect(v.write("attachments/file-1.bin", bytes, null)).rejects.toThrow(/read-only/);
  });

  it("the server spills large files to disk and serves them back", () => {
    const files = new Map<string, { data: Uint8Array; etag: string }>();
    const spill = spillToDisk(files, 1024);
    try {
      const big = attachmentBytes(1, 1, 5000);
      files.set("big", { data: big, etag: '"1"' });
      files.set("small", { data: new Uint8Array(10), etag: '"2"' });
      expect(spill.bytesInMemory()).toBe(10);
      expect(spill.bytesOnDisk()).toBe(5000);
      expect(files.get("big")!.data).toEqual(big);
      expect(files.get("big")!.etag).toBe('"1"');
      files.delete("big");
      expect(spill.bytesOnDisk()).toBe(0);
    } finally {
      spill.dispose();
    }
  });

  it("a first sync of 24 × 4 MB attachments keeps no attachment bytes on any side, and B gets A's bytes", async () => {
    const dav = fakeWebdav({ baseUrl: URL_, username: "u", password: "p", preCreated: true });
    const spill = spillToDisk(dav.files);
    const provider = () => webdavProvider({ url: URL_, username: "u", password: "p" }, { fetch: fakeFetch(dav.handle) });
    try {
      const aNotes = memoryFiles();
      aNotes.set("notes/a.md", "# שלום\n\nhello\n");
      const a = virtualAttachments(aNotes, { seed: 42, count: 24, each: 4 * MB });
      const created = await createVault(provider(), "a long test passphrase 2026");
      const syncA = new E2eeSync({ provider: provider(), keys: created.keys, local: a, store: memoryStateStore() });
      await syncA.markCreated(created.anchor);
      expect((await syncA.sync()).uploaded).toBe(25);

      const { keys } = await unlockVault(provider(), "a long test passphrase 2026");
      const bNotes = memoryFiles();
      const b = hashOnlyFiles(bNotes);
      const syncB = new E2eeSync({ provider: provider(), keys, local: b, store: memoryStateStore() });
      expect((await syncB.sync()).downloaded).toBe(25);

      // 96 MB went through; the server's map, A and B hold none of it.
      expect(spill.bytesOnDisk()).toBeGreaterThan(96 * MB);
      expect(spill.bytesInMemory()).toBeLessThan(MB);
      expect([...aNotes.files.values()].reduce((n, d) => n + d.length, 0)).toBeLessThan(1024);
      expect([...bNotes.files.values()].reduce((n, d) => n + d.length, 0)).toBeLessThan(1024);
      const aHash = new Map((await a.list()).map((f) => [f.path, f.hash]));
      for (const p of a.paths) expect(b.hashes.get(p)).toEqual({ hash: aHash.get(p), size: 4 * MB });
      expect(bNotes.text("notes/a.md")).toBe("# שלום\n\nhello\n");
    } finally {
      spill.dispose();
    }
  }, 120_000);
});
